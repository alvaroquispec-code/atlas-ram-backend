-- Atlas RAM · V9: módulo de inventario de antibióticos (farmacia).
--
-- 1. Rol PHARMACIST: la farmacia registra ingresos, consumos y bajas de su establecimiento.
--    Igual que en V6, se reemplaza la restricción que generó Hibernate en las bases anteriores a Flyway.
-- 2. Antibiotic.aware_category: grupo AWaRe de la OMS (clasificación 2023). Sirve para el indicador
--    de consumo por grupo y como modificador de criticidad del nivel de servicio.
-- 3. Facility.beds / occupancy_rate: para calcular días-cama en el indicador DDD por 100 camas-día.
-- 4. stock_item, stock_lot, stock_movement: ítems (antibiótico + presentación por establecimiento),
--    lotes con fecha de vencimiento (FEFO) y el kardex de movimientos.

alter table app_user drop constraint if exists app_user_role_check;
alter table app_user add constraint app_user_role_check
    check (role in ('ADMIN', 'LAB_TECHNICIAN', 'EPIDEMIOLOGIST', 'PUBLIC_VIEWER', 'PHARMACIST'));

-- AWaRe --------------------------------------------------------------------
alter table antibiotic add column aware_category varchar(20)
    check (aware_category in ('ACCESS', 'WATCH', 'RESERVE', 'NOT_RECOMMENDED'));

-- Clasificación AWaRe 2023 de la OMS para los códigos del catálogo inicial.
-- Los códigos que no estén aquí quedan sin grupo y el administrador lo completa.
update antibiotic set aware_category = 'ACCESS'
 where code in ('AMP', 'SAM', 'OXA', 'CZO', 'GEN', 'AMK', 'SXT', 'NIT', 'CLI');
update antibiotic set aware_category = 'WATCH'
 where code in ('TZP', 'CRO', 'CAZ', 'FEP', 'ETP', 'IPM', 'MEM', 'CIP', 'LVX', 'VAN', 'ERY');
update antibiotic set aware_category = 'RESERVE'
 where code in ('LNZ');

-- Camas del establecimiento ---------------------------------------------------
alter table facility add column beds integer check (beds > 0);
alter table facility add column occupancy_rate numeric(4,3) check (occupancy_rate > 0 and occupancy_rate <= 1);

-- Ítems de inventario -------------------------------------------------------
create table stock_item (
    id bigint generated by default as identity primary key,
    facility_id bigint not null references facility (id),
    antibiotic_id bigint not null references antibiotic (id),
    presentation varchar(100) not null,
    -- gramos de principio activo por unidad (vial, tableta); para el indicador DDD
    grams_per_unit numeric(10,4) not null check (grams_per_unit > 0),
    -- DDD de la OMS para la VÍA de esta presentación (índice ATC/DDD); nulo si no se conoce
    ddd_grams numeric(10,4) check (ddd_grams > 0),
    unit_cost numeric(12,2) check (unit_cost >= 0),
    ven_class varchar(20) not null check (ven_class in ('VITAL', 'ESSENTIAL', 'NON_ESSENTIAL')),
    review_period_days integer not null default 30 check (review_period_days between 1 and 365),
    lead_time_days integer not null default 15 check (lead_time_days between 0 and 365),
    -- nivel de servicio por ciclo; nulo = se deriva de la criticidad (VEN y AWaRe)
    service_level numeric(4,3) check (service_level >= 0.5 and service_level <= 0.999),
    quantity_on_order integer not null default 0 check (quantity_on_order >= 0),
    active boolean not null default true,
    created_at timestamp(6) with time zone not null default now(),
    constraint uk_stock_item unique (facility_id, antibiotic_id, presentation)
);

create table stock_lot (
    id bigint generated by default as identity primary key,
    stock_item_id bigint not null references stock_item (id) on delete cascade,
    lot_number varchar(50) not null,
    expiry_date date not null,
    quantity_received integer not null check (quantity_received > 0),
    quantity_on_hand integer not null check (quantity_on_hand >= 0),
    received_on date not null,
    constraint uk_stock_lot unique (stock_item_id, lot_number),
    constraint ck_stock_lot_on_hand check (quantity_on_hand <= quantity_received)
);
create index idx_stock_lot_fefo on stock_lot (stock_item_id, expiry_date) where quantity_on_hand > 0;

create table stock_movement (
    id bigint generated by default as identity primary key,
    stock_item_id bigint not null references stock_item (id) on delete cascade,
    lot_id bigint references stock_lot (id) on delete cascade,
    type varchar(20) not null check (type in ('RECEIPT', 'CONSUMPTION', 'WRITE_OFF')),
    quantity integer not null check (quantity > 0),
    movement_date date not null,
    note varchar(500),
    created_by bigint references app_user (id),
    created_at timestamp(6) with time zone not null default now()
);
create index idx_stock_movement_series on stock_movement (stock_item_id, type, movement_date);
