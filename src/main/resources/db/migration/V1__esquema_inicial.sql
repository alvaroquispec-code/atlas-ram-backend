-- Atlas RAM · V1: esquema inicial.
-- Es exactamente el DDL que Hibernate generaba a partir de las entidades con ddl-auto=update.
-- En una base que ya tenía estas tablas (producción), Flyway hace un baseline en la versión 1
-- y no ejecuta este archivo. En una base vacía (desarrollo, CI) lo ejecuta completo.

-- Tablas -------------------------------------------------------------------

create table district (
    id bigint generated by default as identity,
    department varchar(100),
    name varchar(100) not null,
    province varchar(100),
    ubigeo varchar(6) not null,
    primary key (id)
);

create table facility (
    id bigint generated by default as identity,
    code varchar(20) not null,
    name varchar(200) not null,
    district_id bigint not null,
    primary key (id)
);

create table app_user (
    id bigint generated by default as identity,
    active boolean not null,
    created_at timestamp(6) with time zone not null,
    email varchar(150) not null,
    full_name varchar(150) not null,
    password_hash varchar(100) not null,
    role varchar(30) not null check (role in ('ADMIN','LAB_TECHNICIAN','EPIDEMIOLOGIST','PUBLIC_VIEWER')),
    primary key (id)
);

create table user_facility (
    user_id bigint not null,
    facility_id bigint not null,
    primary key (user_id, facility_id)
);

create table microorganism (
    id bigint generated by default as identity,
    code varchar(10) not null,
    genus varchar(100) not null,
    gram_stain varchar(20) check (gram_stain in ('POSITIVE','NEGATIVE','NOT_APPLICABLE')),
    species varchar(100),
    primary key (id)
);

create table antibiotic (
    id bigint generated by default as identity,
    antibiotic_class varchar(100),
    code varchar(10) not null,
    name varchar(100) not null,
    primary key (id)
);

create table facility_antibiotic_panel (
    facility_id bigint not null,
    antibiotic_id bigint not null,
    primary key (facility_id, antibiotic_id)
);

create table breakpoint (
    id bigint generated by default as identity,
    resistant_min numeric(10,4),
    standard varchar(20) not null,
    susceptible_max numeric(10,4),
    version varchar(10) not null,
    antibiotic_id bigint not null,
    microorganism_id bigint not null,
    primary key (id)
);

create table data_upload (
    id bigint generated by default as identity,
    error_log TEXT,
    failed_rows integer,
    file_name varchar(255) not null,
    finished_at timestamp(6) with time zone,
    processed_rows integer,
    started_at timestamp(6) with time zone not null,
    status varchar(20) not null check (status in ('PENDING','PROCESSING','COMPLETED','FAILED','REVERTED')),
    total_rows integer,
    facility_id bigint not null,
    uploaded_by bigint not null,
    primary key (id)
);

create table isolate (
    id bigint generated by default as identity,
    collection_date date not null,
    patient_age integer,
    patient_sex varchar(1),
    specimen_type varchar(30) not null check (specimen_type in ('BLOOD','URINE','RESPIRATORY','WOUND','CSF','STOOL','OTHER')),
    data_upload_id bigint,
    district_id bigint,
    facility_id bigint not null,
    microorganism_id bigint not null,
    primary key (id)
);

create table susceptibility_result (
    id bigint generated by default as identity,
    breakpoint_standard varchar(20),
    breakpoint_version varchar(10),
    disk_diffusion_mm integer,
    interpretation varchar(20) not null check (interpretation in ('SUSCEPTIBLE','INTERMEDIATE','RESISTANT')),
    mic_value numeric(10,4),
    reported_interpretation varchar(20) check (reported_interpretation in ('SUSCEPTIBLE','INTERMEDIATE','RESISTANT')),
    antibiotic_id bigint not null,
    isolate_id bigint not null,
    primary key (id)
);

