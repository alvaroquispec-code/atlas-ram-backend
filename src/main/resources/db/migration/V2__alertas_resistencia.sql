-- Atlas RAM · V2: alertas de brote de resistencia.
-- Una alerta agrupa un establecimiento, un microorganismo y una clase de antibiótico, para que un
-- mismo brote (por ejemplo, una carbapenemasa que hace resistentes a imipenem, meropenem y
-- ertapenem a la vez) genere una sola alerta y no una por antibiótico.

create table resistance_alert (
    id bigint generated by default as identity,
    facility_id bigint not null,
    microorganism_id bigint not null,
    antibiotic_id bigint not null,
    antibiotic_class varchar(100) not null,
    status varchar(20) not null check (status in ('OPEN','ACKNOWLEDGED','CLOSED')),
    window_start date not null,
    window_end date not null,
    tested_count integer not null,
    resistant_count integer not null,
    baseline_tested integer not null,
    baseline_resistant integer not null,
    p_value float(53) not null,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone not null,
    closed_at timestamp(6) with time zone,
    primary key (id)
);

alter table resistance_alert add constraint fk_alert_facility foreign key (facility_id) references facility;
alter table resistance_alert add constraint fk_alert_microorganism foreign key (microorganism_id) references microorganism;
alter table resistance_alert add constraint fk_alert_antibiotic foreign key (antibiotic_id) references antibiotic;

-- Deduplicación a nivel de base de datos: solo puede haber una alerta activa por combinación.
create unique index uk_alert_active on resistance_alert (facility_id, microorganism_id, antibiotic_class)
    where status <> 'CLOSED';

create index idx_alert_status on resistance_alert (status);
